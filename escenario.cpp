#include "escenario.hpp"
#include <string>

using namespace std;

vector<Bloque> GenerarMapa()
{
	vector<string> mapa = {
		"111111111111111111111111111111",
		"100000000000000000000000000001",
		"100000000000000100000000000001",
		"100000010000000000000000000001",
		"111110000000000000000000000001",
		"100000000000000000000000000001",
		"100001110100000000000000000001",
		"111000000000100000000000000001",
		"100000000000000000000000000001",
		"100000100000000000000000000001",
		"100000000000000000000000000001",
		"100000000000000000000000000001",
		"100000000000000000000000000001",
		"100000000000000001110000000001",
		"100000000000000000000000000001",
		"100000000001111000000000000001",
		"111111111111111111111001111111",
	};

	vector<Bloque> bloques;
	int tam_bloq = 32;
	int indi_fila = 0;
	int indi_colu = 0;

	for (string s : mapa)
	{
		for (char c : s)
		{
			if (c == '1')
			{
				bloques.push_back(
					Bloque{ { (float)indi_colu * tam_bloq,
							  (float)indi_fila * tam_bloq }, 0.0f });
			}
			indi_colu++;
		}
		indi_fila++;
		indi_colu = 0;
	}

    return bloques;
}
